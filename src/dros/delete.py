GENERATED_HEADER = "# Generated by DROS. Manual changes will be overwritten."
VIRTUAL_INTERFACE_TYPES = frozenset({"gre", "wireguard", "vlan", "bridge"})
SUPPORTED_KINDS = frozenset({"Interface", "CronJob", "Gateway"})


@dataclass(frozen=True)
class FileRemoval:
    path: str
    sha256: str


@dataclass(frozen=True)
class ResourceRemoval:
    kind: str
    name: str
    source: Path
    files: tuple[FileRemoval, ...]
    interface_type: str | None = None
    installed_interface_files: tuple[str, ...] = ()
    runtime_present: bool | None = None
    xfrm: XfrmRemoval | None = None

    @property
    def label(self) -> str:
        return f"{self.kind}/{self.name}"


@dataclass(frozen=True)
class DeletePlan:
    resources: tuple[ResourceRemoval, ...]
    offline: bool


def _safe_name(name: str, *, interface: bool = False) -> None:
    limit = 15 if interface else 128
    if (
        not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.:-]*", name)
        or name in {".", ".."}
        or len(name) > limit
    ):
        raise ValueError(f"unsafe {'interface' if interface else 'resource'} name: {name!r}")


def _select(configs: ConfigStore, target: str) -> list[ConfigObject]:
    parts = target.split("/")
    if len(parts) not in {1, 2} or any(not part or part != part.strip() for part in parts):
        raise ValueError("delete requires kind or kind/name; an empty/all target is not supported")
    kind = resolve_kind_alias(parts[0])
    if resolve_kind_group(kind) is not None:
        raise ValueError(f"delete does not accept group {kind}; select an explicit resource kind")
    if kind not in SUPPORTED_KINDS:
        raise ValueError(
            f"delete is not supported for {kind}; shared/generated state needs a kind-specific "
            "uninstall implementation (edit shared configuration and use gw update as appropriate)"
        )
    selected = configs.by_kind(kind)
    if len(parts) == 2:
        selected = [obj for obj in selected if obj.name == parts[1]]
    if not selected:
        raise ValueError(f"ConfigObject not found: {target}; keep its source YAML until uninstall")
    for obj in selected:
        _safe_name(obj.name, interface=obj.kind == "Interface")
    return selected


def _strings(value: Any, path: str = "spec"):
    if isinstance(value, str):
        yield path, value
    elif isinstance(value, dict):
        for key, child in value.items():
            yield from _strings(child, f"{path}.{key}")
    elif isinstance(value, list):
        for index, child in enumerate(value):
            yield from _strings(child, f"{path}[{index}]")


def _references(obj: ConfigObject, name: str, *, address: bool = False) -> list[str]:
    # Whole identifier matching also covers raw rules/scripts and interface/name.
    # Do not print field values: ConfigMaps and commands may contain secrets.
    boundary = r"A-Za-z0-9_." if address and ":" not in name else r"A-Za-z0-9_.:-"
    pattern = re.compile(r"(?<![" + boundary + "])" + re.escape(name) + r"(?![" + boundary + "])")
    return [path for path, value in _strings(obj.spec) if pattern.search(value)]


def _interface_config(obj: ConfigObject) -> InterfaceConfig:
    try:
        return InterfaceConfig.model_validate(obj.spec)
    except ValidationError as exc:
        fields = ", ".join("spec." + ".".join(map(str, error["loc"])) for error in exc.errors())
        raise ValueError(f"Interface/{obj.name}: invalid configuration at {fields}") from None


def _addresses(obj: ConfigObject) -> set[str]:
    if obj.kind != "Interface":
        return set()
    config = _interface_config(obj)
    values = [
        config.address,
        config.local_vip,
        config.remote_vip,
        *config.addresses,
        *config.extra_addresses,
    ]
    result: set[str] = set()
    for value in values:
        if value:
            try:
                result.add(str(ipaddress.ip_interface(value).ip))
            except ValueError:
                raise ValueError(f"Interface/{obj.name}: invalid interface address") from None
    return result


def _ordered_selection(configs: ConfigStore, selected: list[ConfigObject]) -> list[ConfigObject]:
    chosen = {obj.key for obj in selected}
    errors: list[str] = []
    dependencies: dict[str, set[str]] = {obj.name: set() for obj in selected}
    for target in selected:
        if target.kind not in {"Interface", "Gateway"}:
            continue
        addresses = _addresses(target)
        for other in configs.objects():
            if other.key == target.key:
                continue
            paths = set(_references(other, target.name))
            for address in addresses:
                address_paths = _references(other, address, address=True)
                if other.kind == "Interface":
                    # Multiple point-to-point tunnels may deliberately share
                    # their local VIP; assigning an address is not a dependency.
                    address_paths = [
                        path
                        for path in address_paths
                        if not re.fullmatch(
                            r"spec\.(address|localVip|local_vip|addresses\[\d+\]|"
                            r"extraAddresses\[\d+\]|extra_addresses\[\d+\])",
                            path,
                        )
                    ]
                paths.update(address_paths)
            if not paths:
                continue
            if other.key in chosen:
                dependencies[other.name].add(target.name)
            else:
                errors.extend(
                    f"{target.kind}/{target.name} is referenced by "
                    f"{other.kind}/{other.name} at {path} ({other.source}); "
                    "remove or migrate that reference first"
                    for path in sorted(paths)
                )
    if errors:
        raise ValueError("\n".join(errors))
    ordered: list[ConfigObject] = []
    pending = {obj.name: obj for obj in selected}
    # Dependents before parents, for example VLAN before bridge.
    while pending:
        parents = set().union(*(dependencies[name] for name in pending))
        ready = sorted(set(pending) - parents)
        if not ready:
            raise ValueError("delete selection has cyclic references; remove them first")
        for name in ready:
            ordered.append(pending.pop(name))
    return ordered


def _target_path(settings: DrosSettings, logical: str) -> Path:
    path = Path(logical)
    root = settings.sys_root
    if not root.is_absolute() or not path.is_absolute() or ".." in path.parts or ".." in root.parts:
        raise ValueError(f"unsafe managed path: {logical}")
    target = root / path.relative_to("/")
    for candidate in [target, *target.parents]:
        if candidate.is_symlink():
            raise ValueError(f"refusing symlink in managed path: {candidate}")
    return target


def _managed_file(
    settings: DrosSettings, path: str, *, expected: str | None = None
) -> FileRemoval | None:
    target = _target_path(settings, path)
    if not target.exists():
        return None
    info = target.stat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise ValueError(f"refusing non-regular or multiply-linked managed file: {path}")
    raw = target.read_bytes()
    content = raw.decode("utf-8")
    if not content.startswith(GENERATED_HEADER + "\n"):
        raise ValueError(f"file is not marked as generated by DROS: {path}")
    if expected is not None and content != expected:
        raise ValueError(
            f"installed configuration differs from source: {path}; reconcile before delete"
        )
    return FileRemoval(path, hashlib.sha256(raw).hexdigest())


def _links(runner: CommandRunner) -> list[dict[str, Any]]:
    command = ["ip", "-json", "-details", "link", "show"]
    result = runner(command, check=False, text=True, capture_output=True, timeout=30)
    if result.returncode:
        raise RuntimeError("cannot inspect kernel interfaces; no deletion was attempted")
    data = json.loads(result.stdout)
    if not isinstance(data, list) or any(not isinstance(item, dict) for item in data):
        raise ValueError("invalid ip link inventory; no deletion was attempted")
    return data


def _check_xfrm_runtime_sharing(resource: ResourceRemoval, links: list[dict[str, Any]]) -> None:
    if not resource.xfrm:
        return
    direction = resource.xfrm.directions[0]
    for other in links:
        if other.get("ifname") == resource.name:
            continue
        info = other.get("linkinfo", {})
        if info.get("info_kind") not in {"gre", "gretap", "ip6gre", "ip6gretap"}:
            continue
        data = info.get("info_data", {})
        wildcard_remote = data.get("remote") in {"0.0.0.0", "::", None}
        active_wildcard = wildcard_remote and (
            "UP" in other.get("flags", []) or data.get("collect_metadata") is True
        )
        if (data.get("remote") == direction.dst or active_wildcard) and data.get("local") in {
            direction.src,
            "0.0.0.0",
            "::",
            None,
        }:
            raise ValueError(
                f"XfrmTransport/{resource.xfrm.name} is shared: runtime Interface/"
                f"{other.get('ifname')} uses the same GRE endpoints; refusing uninstall"
            )


def _check_runtime(
    resource: ResourceRemoval, links: list[dict[str, Any]], selected: set[str]
) -> bool:
    _check_xfrm_runtime_sharing(resource, links)
    link = next((item for item in links if item.get("ifname") == resource.name), None)
    if link is None:
        return False
    if link.get("linkinfo", {}).get("info_kind") != resource.interface_type:
        raise ValueError(f"{resource.label}: runtime interface type differs; refusing deletion")
    if resource.xfrm:
        data = link.get("linkinfo", {}).get("info_data", {})
        direction = resource.xfrm.directions[0]
        if data.get("local") != direction.src or data.get("remote") != direction.dst:
            raise ValueError(f"{resource.label}: GRE endpoints differ from XFRM source ownership")
    if not resource.installed_interface_files:
        raise ValueError(
            f"{resource.label}: live interface has no matching DROS configuration; "
            "ownership cannot be established"
        )
    for other in links:
        if other.get("ifname") in selected:
            continue
        if (
            other.get("master") in {resource.name, link.get("ifindex")}
            or other.get("link_index") == link.get("ifindex")
            or other.get("link") == resource.name
        ):
            raise ValueError(
                f"{resource.label}: runtime dependent Interface/{other.get('ifname')} "
                "must be detached or removed first"
            )
    return True


def build_delete_plan(
    settings: DrosSettings, target: str, *, runner: CommandRunner = subprocess.run
) -> DeletePlan:
    configs = load_config_objects(settings)
    all_configs = load_config_objects(settings, include_disabled=True)
    selected = _ordered_selection(all_configs, _select(configs, target))
    executor = SystemExecutor(settings, verbose=0, runner=runner)
    context = UpdateContext(settings, configs, executor, create_default_registry())
    resources: list[ResourceRemoval] = []
    for obj in selected:
        files: list[FileRemoval] = []
        if obj.kind == "Gateway":
            # Gateways are pure inputs to RouteTable, with no independently owned state.
            resources.append(ResourceRemoval(obj.kind, obj.name, obj.source, ()))
            continue
        if obj.kind == "CronJob":
            file = _managed_file(settings, _cron_path(obj.name))
            if file:
                content = _target_path(settings, file.path).read_text()
                if f"# Resource: CronJob/{obj.name}\n" not in content:
                    raise ValueError(f"{file.path}: generated file belongs to a different resource")
                files.append(file)
            resources.append(ResourceRemoval(obj.kind, obj.name, obj.source, tuple(files)))
            continue
        config = _interface_config(obj)
        if config.type not in VIRTUAL_INTERFACE_TYPES:
            raise ValueError(
                f"Interface/{obj.name}: delete does not support type {config.type}; "
                "physical, external and service-backed interfaces need their own lifecycle"
            )
        xfrm = None
        if config.xfrm_transport:
            if config.type != "gre":
                raise ValueError(
                    f"Interface/{obj.name}: automatic XFRM uninstall supports GRE only"
                )
            xfrm = plan_xfrm(all_configs, obj, config.xfrm_transport)
            direction = xfrm.directions[0]
            if (config.local_public_ip, config.remote_public_ip) != (direction.src, direction.dst):
                raise ValueError(
                    f"Interface/{obj.name}: GRE endpoints do not match XfrmTransport/{xfrm.name}"
                )
            unit_path = f"/etc/systemd/system/{xfrm.service}"
            unit_file = _managed_file(settings, unit_path, expected=_render_xfrm_service(xfrm.name))
            if unit_file:
                files.append(unit_file)
                xfrm = replace(xfrm, service_file=unit_path)
        iface_dir = _target_path(settings, IFUPDOWN_DIR)
        candidates = {f"{IFUPDOWN_DIR}/dros-{obj.name}.cfg"}
        if iface_dir.exists():
            candidates.update(
                f"{IFUPDOWN_DIR}/{path.name}" for path in iface_dir.glob(f"*-dros-{obj.name}.cfg")
            )
        expected = _render_interface(context, obj.name, config, _devgroups(context, []))
        iface_files: list[str] = []
        for path in sorted(candidates):
            file = _managed_file(settings, path, expected=expected)
            if file:
                files.append(file)
                iface_files.append(path)
        if config.type == "wireguard":
            path = f"/etc/wireguard/{obj.name}.conf"
            file = _managed_file(
                settings, path, expected=_render_wireguard_conf(context, obj, config)
            )
            if file:
                files.append(file)
            path = f"/etc/cron.d/dros-wgsd-client-{obj.name}"
            file = _managed_file(settings, path)
            if file:
                if (
                    f"# Resource: Interface/{obj.name} wgsdClient\n"
                    not in _target_path(settings, path).read_text()
                ):
                    raise ValueError(f"{path}: generated file belongs to a different resource")
                files.insert(0, file)
        nft_path = f"/etc/dros/nftables.d/30-interface-{obj.name}.nft"
        nft_file = _managed_file(settings, nft_path)
        if nft_file:
            if any(
                line.strip() and not line.lstrip().startswith("#")
                for line in _target_path(settings, nft_path).read_text().splitlines()
            ):
                raise ValueError(
                    f"Interface/{obj.name}: active shared-firewall listen rules remain; "
                    "remove listenPort/listen from source and run gw update first"
                )
            files.append(nft_file)
        resources.append(
            ResourceRemoval(
                obj.kind,
                obj.name,
                obj.source,
                tuple(files),
                config.type,
                tuple(iface_files),
                xfrm=xfrm,
            )
        )
    offline = settings.sys_root != Path("/")
    if not offline and any(item.interface_type for item in resources):
        links = _links(runner)
        chosen = {item.name for item in resources if item.interface_type}
        resources = [
            ResourceRemoval(
                item.kind,
                item.name,
                item.source,
                item.files,
                item.interface_type,
                item.installed_interface_files,
                _check_runtime(item, links, chosen) if item.interface_type else None,
                item.xfrm,
            )
            for item in resources
        ]
        for item in resources:
            if item.xfrm:
                inspect_service(item.xfrm, runner)
                inspect_xfrm(item.xfrm, runner)
    return DeletePlan(tuple(resources), offline)


def print_delete_plan(plan: DeletePlan, console: Console) -> None:
    console.print("Uninstall plan (source YAML is retained):", markup=False)
    if plan.offline:
        console.print("Offline sysRoot: kernel/service commands will be skipped.", markup=False)
    for resource in plan.resources:
        console.print(f"{resource.label} (source: {resource.source})", markup=False)
        if resource.interface_type:
            if resource.runtime_present is not False:
                if resource.installed_interface_files:
                    console.print(
                        "  run: " + shlex.join(["ifdown", "--force", resource.name]), markup=False
                    )
                    console.print(
                        "    ifdown also runs installed down hooks, which may queue route refreshes",
                        markup=False,
                    )
                console.print(
                    "  if interface remains: "
                    + shlex.join(["ip", "link", "delete", "dev", resource.name]),
                    markup=False,
                )
                console.print(
                    "  verify: interface is absent; abort on failure before removing files",
                    markup=False,
                )
            else:
                console.print("  interface already absent; skip kernel commands", markup=False)
        if resource.xfrm:
            xfrm = resource.xfrm
            console.print(
                f"  exclusive XfrmTransport/{xfrm.name} (source retained: {xfrm.source})",
                markup=False,
            )
            if xfrm.service_file:
                console.print(
                    "  run: " + shlex.join(["systemctl", "disable", "--now", xfrm.service]),
                    markup=False,
                )
                console.print("  verify: systemd unit inactive and disabled", markup=False)
            for direction in xfrm.directions:
                console.print("  if present: " + shlex.join(direction.policy_command), markup=False)
            for direction in xfrm.directions:
                console.print("  if present: " + shlex.join(direction.state_command), markup=False)
            console.print(
                "  verify: ip -oneline xfrm policy list; ip -oneline xfrm state list nokeys; "
                "target entries absent (keys never displayed)",
                markup=False,
            )
        for file in resource.files:
            console.print(f"  delete file: {file.path}", markup=False)
        if resource.xfrm and resource.xfrm.service_file:
            console.print("  run: systemctl daemon-reload", markup=False)
        if resource.kind == "Gateway":
            console.print(
                "  logical declaration only; no independently owned system state", markup=False
            )
            console.print(
                "  apply RouteTable changes with gw update before removing this declaration",
                markup=False,
            )
        elif resource.kind == "CronJob":
            console.print(
                "  prevents future cron starts; already running jobs are not terminated",
                markup=False,
            )
        elif not resource.files and resource.runtime_present is False:
            console.print("  already absent", markup=False)
    console.print(
        "Remove the selected YAML documents manually after a successful uninstall. "
        "Keeping them allows a later gw update/bootstrap or hook to reinstall state. "
        "Shared files, packages, keys supplied by path and persistent data are retained.",
        markup=False,
    )


def apply_delete_plan(
    settings: DrosSettings,
    plan: DeletePlan,
    *,
    runner: CommandRunner = subprocess.run,
    console: Console | None = None,
) -> None:
    """Apply while the caller holds the normal gateway apply lock; stop on first failure.

    File hashes are checked for the entire batch before any mutation and again
    before unlinking. Failure is partial, not an implicit rollback/reinstallation.
    """
    if plan.offline != (settings.sys_root != Path("/")):
        raise ValueError("plan sysRoot mode differs from apply settings")

    def verify(file: FileRemoval) -> None:
        current = _managed_file(settings, file.path)
        if current != file:
            raise ValueError(
                f"managed file changed since planning: {file.path}; rerun delete preview"
            )

    for resource in plan.resources:
        for file in resource.files:
            verify(file)
    # Validate every transport before touching any member of a batch.
    for resource in plan.resources:
        if resource.xfrm and not plan.offline:
            inspect_service(resource.xfrm, runner)
            inspect_xfrm(resource.xfrm, runner)
    for resource in plan.resources:
        try:
            if resource.interface_type and not plan.offline:
                # Recheck type/dependents just before touching each interface.
                if _check_runtime(resource, _links(runner), {resource.name}):
                    _run(runner, ["ifdown", "--force", resource.name])
                    if _check_runtime(resource, _links(runner), {resource.name}):
                        _run(runner, ["ip", "link", "delete", "dev", resource.name])
                    if any(item.get("ifname") == resource.name for item in _links(runner)):
                        raise RuntimeError("interface still exists after uninstall")
            if resource.xfrm and not plan.offline:
                xfrm = resource.xfrm
                if xfrm.service_file:
                    _run(runner, ["systemctl", "disable", "--now", xfrm.service])
                    result = runner(
                        ["systemctl", "show", xfrm.service, "--property=ActiveState,UnitFileState"],
                        check=False,
                        text=True,
                        capture_output=True,
                        timeout=30,
                    )
                    values = dict(
                        line.split("=", 1) for line in result.stdout.splitlines() if "=" in line
                    )
                    if (
                        result.returncode
                        or values.get("ActiveState") not in {"inactive", "failed"}
                        or values.get("UnitFileState") not in {"disabled", "static"}
                    ):
                        raise RuntimeError(
                            f"{xfrm.service}: could not verify stopped/disabled state"
                        )
                uninstall_xfrm(xfrm, runner)
            for file in resource.files:
                verify(file)
                _target_path(settings, file.path).unlink()
            if resource.xfrm and resource.xfrm.service_file and not plan.offline:
                _run(runner, ["systemctl", "daemon-reload"])
            if console:
                console.print(f"uninstalled {resource.label}", markup=False)
        except (OSError, RuntimeError, ValueError, subprocess.SubprocessError) as exc:
            raise RuntimeError(
                f"uninstall stopped at {resource.label}; earlier actions may have "
                "completed, no rollback was attempted; source YAML is retained. "
                f"Cause: {exc}"
            ) from exc


def _run(runner: CommandRunner, command: list[str]) -> None:
    result = runner(command, check=False, text=True, capture_output=True, timeout=60)
    if result.returncode:
        # Do not print arbitrary hook output, which can contain configuration secrets.
        raise RuntimeError(f"command failed ({result.returncode}): {shlex.join(command)}")
